-- Создайте алиас:
-- name: BotWait
-- regex: ^\.пауза\s+(?<sec>[0-9]+(?:[.,][0-9]+)?)$
-- body:
-- =====================================================================
-- Алиас ".пауза <сек>" — шаг ожидания в маршруте.
--
--   * при записи (.бот запись старт <зона>) — добавляет шаг { wait = N };
--   * вне записи — подсказывает, что пауза бота делается через .бот пауза.
--
-- Реализация: скрипт BotCore (botCore.lua).
-- =====================================================================

if not Bot then
  cecho("<red>[Bot] скрипт BotCore не загружен — алиас не работает\n")
  return
end

local sec = tonumber((tostring(matches.sec or ""):gsub(",", ".")))
if Bot.state == "record" then
  Bot.record_wait(sec)
else
  Bot.warn("<gray>Пауза в маршрут пишется только при записи: " ..
    "<yellow>.бот запись старт «зона»<gray>. Пауза бота: <yellow>.бот пауза 1")
end
