-- Создайте алиас:
-- name: BotTrig
-- regex: ^\.триг\s+(?<cmd>.+)$
-- body:
-- =====================================================================
-- Алиас ".триг <команда>" — действие, которое бот выполнит в этой комнате.
--
--   * при записи (.бот запись старт <зона>) — добавляет шаг в маршрут;
--   * вне записи — просто отправляет команду на сервер.
--
-- Реализация: скрипт BotCore (botCore.lua).
-- =====================================================================

if not Bot then
  cecho("<red>[Bot] скрипт BotCore не загружен — алиас не работает\n")
  return
end

local cmd = matches.cmd or ""
if Bot.state == "record" then
  Bot.record_action(cmd)
else
  -- как ввод из командной строки: работают алиасы профиля («оов шкаф»)
  Bot.run_action(cmd)
end
