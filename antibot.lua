-- Проверяем наличие осмысленных слов через frontier pattern
local lowerLine = utf8.lower(line)

-- Точные слова (местоимения, названия, короткие основы < 4 букв, нерегулярные формы)
for _, word in ipairs(safeWords) do
  local pattern = "%f[%a]" .. word .. "%f[%A]"
  if utf8.find(lowerLine, pattern) then
    return -- содержит осмысленное слово — не анти-бот
  end
end

-- Подставляем окончания к основам
local function matchStem(stem, endings)
  for _, ending in ipairs(endings) do
    if utf8.find(lowerLine, "%f[%a]" .. stem .. ending .. "%f[%A]") then
      return true
    end
  end

  return false
end

for _, stem in ipairs(verbStemsPresent) do
  if matchStem(stem, verbEndsPresent) then
    return -- содержит осмысленный глагол — не анти-бот
  end
end

for _, stem in ipairs(verbStemsPast) do
  if matchStem(stem, verbEndsPast) then
    return
  end
end

for _, stem in ipairs(nounStems) do
  if matchStem(stem, nounEnds) then
    return
  end
end

for _, stem in ipairs(participleStems) do
  if matchStem(stem, participleEnds) then
    return
  end
end

local function isNewLine(line)
  -- Проверяем, видели ли мы эту строку
  if antiBotSeenLines[line] then
    return false  -- уже видели
  end

  -- Запоминаем строку
  antiBotSeenLines[line] = true
  table.insert(antiBotSeenLinesOrder, line)

  -- Чистим кэш, если он слишком большой
  if #antiBotSeenLinesOrder > antiBotMaxCache then
    local old = table.remove(antiBotSeenLinesOrder, 1)
    antiBotSeenLines[old] = nil
  end

  return true  -- новая строка
end

if not isNewLine(line) then
  return
